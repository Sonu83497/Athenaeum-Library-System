# ============================================================
# CONSTANTS
# ============================================================

MAX_TOOL_ITERATIONS = 5

_rate_limit_log: dict[int, deque] = defaultdict(deque)

RATE_LIMIT_MAX_REQUESTS = 20
RATE_LIMIT_WINDOW_SECONDS = 60


# ============================================================
# ASSISTANT ERROR
# ============================================================

class AssistantError(Exception):
    pass


# ============================================================
# RATE LIMIT
# ============================================================

def check_rate_limit(user_id: int) -> None:
    now = time.time()
    log = _rate_limit_log[user_id]

    while log and now - log[0] > RATE_LIMIT_WINDOW_SECONDS:
        log.popleft()

    if len(log) >= RATE_LIMIT_MAX_REQUESTS:
        raise AssistantError(
            "Too many requests. Please wait a moment before trying again."
        )

    log.append(now)


# ============================================================
# TOOL EXECUTION
# ============================================================

def _execute_tool(
    db: Session,
    member_id: int,
    name: str,
    arguments: dict,
) -> dict:
    entry = TOOL_REGISTRY.get(name)

    if not entry:
        return {
            "error": f"Unknown tool: {name}"
        }

    func, needs_member_id = entry

    try:
        if needs_member_id:
            # SECURITY:
            # Never accept member_id from the LLM.
            return func(
                db,
                member_id=member_id,
            )

        return func(
            db,
            **arguments,
        )

    except TypeError as exc:
        return {
            "error": f"Invalid arguments for {name}: {exc}"
        }

    except Exception as exc:
        return {
            "error": f"Tool execution failed: {exc}"
        }


# ============================================================
# MAIN ASSISTANT
# ============================================================

def ask_assistant(
    db: Session,
    user_id: int,
    member_id: int,
    user_message: str,
) -> str:

    # --------------------------------------------------------
    # VALIDATE MESSAGE
    # --------------------------------------------------------

    if not user_message or not user_message.strip():
        return "Please type a question about the library."

    user_message = user_message.strip()

    if len(user_message) > settings.AI_MAX_INPUT_CHARS:
        return (
            f"Your message is too long. Please limit it to "
            f"{settings.AI_MAX_INPUT_CHARS} characters."
        )

    # --------------------------------------------------------
    # RATE LIMIT
    # --------------------------------------------------------

    check_rate_limit(user_id)

    # --------------------------------------------------------
    # INITIALIZE PROVIDER
    # --------------------------------------------------------

    try:
        provider = get_provider()

    except Exception as exc:
        raise AssistantError(
            f"AI provider initialization failed: {exc}"
        )

    if provider is None:
        raise AssistantError(
            "The AI assistant is not configured. "
            "Set AI_PROVIDER and AI_API_KEY in the backend .env file."
        )

    # --------------------------------------------------------
    # INITIAL MESSAGE
    # --------------------------------------------------------

    messages = [
        {
            "role": "user",
            "content": user_message,
        }
    ]

    # --------------------------------------------------------
    # TOOL / AI LOOP
    # --------------------------------------------------------

    for _ in range(MAX_TOOL_ITERATIONS):

        try:
            response = provider.complete(
                messages=messages,
                tools=TOOLS,
                system=SYSTEM_PROMPT,
            )

        except Exception as exc:
            raise AssistantError(
                f"The AI service is currently unavailable: {exc}"
            )

        # ----------------------------------------------------
        # FINAL RESPONSE
        # ----------------------------------------------------

        if not response.tool_calls:
            return (
                response.text
                or "I don't have enough information to answer that."
            )

        # ----------------------------------------------------
        # ASSISTANT TOOL CALL MESSAGE
        # ----------------------------------------------------

        assistant_content = []

        if response.text:
            assistant_content.append(
                {
                    "type": "text",
                    "text": response.text,
                }
            )

        for tc in response.tool_calls:

            assistant_content.append(
                {
                    "type": "tool_use",
                    "id": tc.id,
                    "name": tc.name,
                    "input": tc.arguments,
                }
            )

        messages.append(
            {
                "role": "assistant",
                "content": assistant_content,
            }
        )

        # ----------------------------------------------------
        # EXECUTE TOOLS
        # ----------------------------------------------------

        tool_result_content = []

        for tc in response.tool_calls:

            result = _execute_tool(
                db=db,
                member_id=member_id,
                name=tc.name,
                arguments=tc.arguments,
            )

            # Keep tool name with result.
            # Required by Gemini conversion logic.
            tool_result_content.append(
                {
                    "type": "tool_result",
                    "tool_use_id": tc.id,
                    "name": tc.name,
                    "content": json.dumps(
                        result,
                        ensure_ascii=False,
                    ),
                }
            )

        # ----------------------------------------------------
        # TOOL RESULT MESSAGE
        # ----------------------------------------------------

        messages.append(
            {
                "role": "user",
                "content": tool_result_content,
            }
        )

    # --------------------------------------------------------
    # MAX ITERATIONS
    # --------------------------------------------------------

    return (
        "I wasn't able to finish processing that request. "
        "Please try rephrasing your question."
    )